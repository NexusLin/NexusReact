use actix_web::web;
pub fn config(cfg: &mut web::ServiceConfig) {
    // 字典类型
    cfg.route(
        "/dictType",
        web::get().to(crate::modules::dict::handlers::get_list),
    )
    .route(
        "/dictType",
        web::post().to(crate::modules::dict::handlers::post_add),
    )
    .route(
        "/dictType",
        web::put().to(crate::modules::dict::handlers::put_update),
    )
    .route(
        "/dictType/optionselect",
        web::get().to(crate::modules::dict::handlers::get_all_dict_type),
    )
    .route(
        "/dictType/{id}",
        web::get().to(crate::modules::dict::handlers::get_detail),
    )
    .route(
        "/dictType/{id}",
        web::delete().to(crate::modules::dict::handlers::del_delete),
    )
    // 字典数据
    .route(
        "/dictData",
        web::get().to(crate::modules::dict::handlers::get_list_data),
    )
    .route(
        "/dictData",
        web::post().to(crate::modules::dict::handlers::post_add_data),
    )
    .route(
        "/dictData",
        web::put().to(crate::modules::dict::handlers::put_update_data),
    )
    .route(
        "/dictData/optionselect",
        web::get().to(crate::modules::dict::handlers::get_all_dict_data),
    )
    .route(
        "/dictData/{id}",
        web::get().to(crate::modules::dict::handlers::get_detail_data),
    )
    .route(
        "/dictData/{id}",
        web::delete().to(crate::modules::dict::handlers::del_delete_data),
    );
}
